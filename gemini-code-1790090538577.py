import streamlit as st
import pandas as pd
import plotly.express as px

# ۱. تنظیمات کلی صفحه اپلیکیشن
st.set_page_config(page_title="اطلس زنبورداری ایران", layout="wide")

st.title("🍯 اطلس جامع زنبورداری ایران")
st.markdown("پلتفرم یکپارچه داده‌های ژنتیکی، پاتولوژی و فولکلور زنبورداری")

# ۲. ساخت پایگاه داده فرضی (در واقعیت این داده‌ها از فایل اکسل یا دیتابیس خوانده می‌شوند)
data = {
    'استان': ['تهران', 'کردستان', 'مازندران'],
    'عرض_جغرافیایی': [35.6892, 35.3113, 36.2262],
    'طول_جغرافیایی': [51.3890, 46.9960, 52.5319],
    'نوع_کندو_سنتی': ['سبدی و جعبه‌ای', 'تنه درختی (کلانه)', 'سبدی سفالی'],
    'درصد_مقاومت_واروآ': [75, 30, 45], # مقاومت فنوتیپی به کنه‌کش‌ها
    'بار_ویروسی_DWV': ['بالا', 'پایین', 'متوسط'],
    'فلور_غالب': ['آویشن و گون', 'گون و سماق', 'مرکبات و جنگلی']
}
df = pd.DataFrame(data)

# ۳. طراحی سایدبار (منوی کناری) برای انتخاب نقش و لنز نقشه
st.sidebar.header("تنظیمات نمایش")
user_role = st.sidebar.radio("شما کی هستید؟", ["پژوهشگر / دانشجو", "علاقه‌مند / زنبوردار"])

lens = st.sidebar.radio("لنز نقشه (لایه اطلاعاتی):", ["لنز فرهنگی (فولکلور)", "لنز علمی (آزمایشگاهی)"])

# ۴. رسم نقشه بر اساس لنز انتخابی کاربر
if lens == "لنز فرهنگی (فولکلور)":
    # در لنز فرهنگی، هاور نقشه اطلاعات نوع کندو و گیاهان را نشان می‌دهد
    fig = px.scatter_map(df, lat="عرض_جغرافیایی", lon="طول_جغرافیایی", 
                            hover_name="استان", hover_data=["نوع_کندو_سنتی", "فلور_غالب"],
                            color_discrete_sequence=["green"], size_max=15, zoom=4.5, height=450)
else:
    # در لنز علمی، رنگ و اندازه نقاط بر اساس درصد مقاومت کنه‌ها تغییر می‌کند
    fig = px.scatter_map(df, lat="عرض_جغرافیایی", lon="طول_جغرافیایی", 
                            hover_name="استان", hover_data=["درصد_مقاومت_واروآ", "بار_ویروسی_DWV"],
                            color="درصد_مقاومت_واروآ", size="درصد_مقاومت_واروآ",
                            color_continuous_scale="Reds", zoom=4.5, height=450)

# تنظیم استایل نقشه
fig.update_layout(map_style="open-street-map", margin={"r":0,"t":0,"l":0,"b":0})
st.plotly_chart(fig, use_container_width=True)

# ۵. بخش پروفایل منطقه‌ای (کارت‌های تب‌بندی شده در زیر نقشه)
st.divider()
st.subheader("پروفایل منطقه‌ای")
selected_region = st.selectbox("یک استان را برای مشاهده جزئیات انتخاب کنید:", df['استان'])

# فیلتر کردن داده‌های استان انتخاب شده
region_data = df[df['استان'] == selected_region].iloc[0]

# ساخت تب‌های مجزا برای جلوگیری از گیج شدن کاربر
tab1, tab2, tab3 = st.tabs(["🏛️ فرهنگ و تاریخچه", "🌸 فلور و گیاه‌شناسی", "🧬 ژنتیک و پاتولوژی"])

with tab1:
    st.write(f"### تاریخچه زنبورداری در {selected_region}")
    st.write(f"**نوع کندوی سنتی رایج:** {region_data['نوع_کندو_سنتی']}")
    st.info("در این بخش گالری تصاویر، ویدیوهای مستند و فایل‌های صوتی مصاحبه با زنبورداران محلی بارگذاری می‌شود.")

with tab2:
    st.write(f"### پوشش گیاهی و عسل منطقه {selected_region}")
    st.write(f"**فلور غالب و شهدزا:** {region_data['فلور_غالب']}")
    st.success("در این تب تقویم زمان شکوفه‌دهی گیاهان منطقه در طول سال نمایش داده می‌شود.")

with tab3:
    st.write(f"### داده‌های آزمایشگاهی و مقاومت آفات در {selected_region}")
    # نمایش متریک‌های عددی جذاب
    col1, col2 = st.columns(2)
    col1.metric(label="درصد مقاومت فنوتیپی کنه واروآ", value=f"{region_data['درصد_مقاومت_واروآ']}%")
    col2.metric(label="سطح بار ویروسی (DWV)", value=region_data['بار_ویروسی_DWV'])
    
    st.warning("در اینجا گراف‌های آنالیز بقا (کاپلان-مایر)، نمودارهای LC50 و پلات‌های بیان ژن‌های ایمنی (مثل *vitellogenin* یا *abaecin*) رندر می‌شوند.")